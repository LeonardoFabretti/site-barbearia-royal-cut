-- Estrutura do banco da Royal Cut (PostgreSQL / Supabase).
-- Rode uma vez, num banco vazio, pelo SQL Editor do Supabase.

-- extensão usada pela trava de horário duplicado
create extension if not exists btree_gist;

create table servicos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nome text not null,
  preco numeric not null,
  duracao_min int not null,
  ativo boolean not null default true,
  categoria text not null default 'masculino'
    check (categoria in ('masculino', 'feminino'))
);

create table profissionais (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nome text not null,
  telefone text,
  ativo boolean not null default true
);

-- dias e horários de trabalho; dia_semana: 0 = domingo ... 6 = sábado.
-- Um dia com almoço vira duas linhas (ex.: 09:00–12:00 e 13:00–19:00).
create table expediente (
  id bigint generated by default as identity primary key,
  profissional_id bigint not null references profissionais(id) on delete cascade,
  dia_semana smallint not null check (dia_semana between 0 and 6),
  inicio time not null,
  fim time not null,
  check (fim > inicio)
);

create table clientes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nome text not null,
  celular text not null unique
);

create table agendamentos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  profissional_id bigint not null references profissionais(id),
  servico_id bigint not null references servicos(id),
  cliente_id bigint not null references clientes(id),
  inicio timestamptz not null,
  fim timestamptz not null,
  preco numeric not null, -- preço do serviço no dia em que foi marcado
  status text not null default 'confirmado'
    check (status in ('confirmado', 'cancelado', 'concluido')),
  check (fim > inicio),
  -- impede dois agendamentos sobrepostos do mesmo profissional (cancelados não contam)
  constraint sem_horario_duplicado exclude using gist (
    profissional_id with =,
    tstzrange(inicio, fim) with &&
  ) where (status <> 'cancelado')
);

-- Protege as tabelas da API pública do Supabase: o site acessa só pelo servidor.
alter table servicos enable row level security;
alter table profissionais enable row level security;
alter table expediente enable row level security;
alter table clientes enable row level security;
alter table agendamentos enable row level security;
